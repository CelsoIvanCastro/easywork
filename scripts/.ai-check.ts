import { chromium } from "playwright-core";
import { readFileSync } from "node:fs";
const PW = readFileSync(".local/demo-credenciales.txt", "utf8").split("\n")[1].trim();
const CID = readFileSync(".local/cid", "utf8").trim();
const br = await chromium.launch({ channel: "chrome", headless: true });
const p = await (await br.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
await p.goto("http://localhost:3000/entrar");
await p.getByLabel("Correo").fill("ceo@demo.test");
await p.getByLabel("Contraseña", { exact: true }).fill(PW);
await p.getByRole("button", { name: "Entrar" }).click();
await p.waitForURL(/empresas/);
await p.goto(`http://localhost:3000/e/${CID}/ia`);
const q = process.argv[2] ?? "¿Cuántas personas activas hay y en qué departamentos?";
await p.getByLabel("Tu pregunta").fill(q);
const t0 = Date.now();
await p.getByRole("button", { name: /Preguntar|Enviar/ }).click();
await p.locator(".card").filter({ hasText: /^IA/ }).first().waitFor({ timeout: 180000 });
console.log(`(${((Date.now() - t0) / 1000).toFixed(1)} s)`, (await p.locator(".card").filter({ hasText: /^IA/ }).first().innerText()).slice(0, 700));
await br.close();
